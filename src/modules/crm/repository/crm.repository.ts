export class RepositorioCrmJson implements IRepositorioCrm {
  async obtenerTodo(): Promise<DatosCrm> {
    return leerJsonSeguro<DatosCrm>(ARCHIVO_CRM, DATOS_CRM_INICIALES);
  }

  async guardarOportunidades(oportunidades: OportunidadCrm[]): Promise<void> {
    await actualizarJsonSeguro<DatosCrm>(ARCHIVO_CRM, DATOS_CRM_INICIALES, (actual) => ({
      ...actual,
      oportunidades,
    }));
  }

  async guardarClientes(clientes: ClienteCrm[]): Promise<void> {
    await actualizarJsonSeguro<DatosCrm>(ARCHIVO_CRM, DATOS_CRM_INICIALES, (actual) => ({
      ...actual,
      clientes,
    }));
  }

  async guardarActividades(actividades: ActividadCrm[]): Promise<void> {
    await actualizarJsonSeguro<DatosCrm>(ARCHIVO_CRM, DATOS_CRM_INICIALES, (actual) => ({
      ...actual,
      actividades,
    }));
  }
}

export const repositorioCrm: IRepositorioCrm = new RepositorioCrmJson();
